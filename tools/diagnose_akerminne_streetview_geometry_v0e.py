def norm(x):
    s = "" if x is None else str(x)
    s = unicodedata.normalize("NFKD", s).encode("ascii","ignore").decode("ascii").lower()
    return re.sub(r"[^a-z0-9]+","_",s).strip("_")

def canon(v):
    s = "" if pd.isna(v) else str(v).strip()
    if re.fullmatch(r"\d+\.0", s): s=s[:-2]
    p=[x.strip() for x in s.split("|")]
    if len(p)>=3 and re.fullmatch(r"20\d{2}",p[0]): s="|".join(p[1:])
    return s

def choose(cols, exact=(), token_sets=()):
    nm={c:norm(c) for c in cols}
    for e in exact:
        en=norm(e)
        for c,n in nm.items():
            if n==en: return c
    for toks in token_sets:
        tt=[norm(t) for t in toks]
        hits=[c for c,n in nm.items() if all(t in n for t in tt)]
        if hits:
            return sorted(hits,key=lambda c:(len(nm[c]),nm[c]))[0]
    return None

def field_col(cols):
    return choose(cols,
        exact=("current_field_id","field_id","m0_field_id","skifte_id","skiftes_id","skiftesid","skifteid"),
        token_sets=(("current","field","id"),("field","id"),("skifte","id")))

def year_col(cols):
    return choose(cols, exact=("year","ar","år","crop_year","odlingsar"),
                  token_sets=(("year",),("odlings","ar")))

def parse_pano(url):
    # URL generated by STOPA: ...?api=1&map_action=pano&viewpoint=lat,lon
    try:
        q=parse_qs(urlparse(str(url)).query)
        v=q.get("viewpoint",[None])[0]
        if v:
            a,b=v.split(",")
            return float(a),float(b)
    except Exception:
        pass
    return None,None

