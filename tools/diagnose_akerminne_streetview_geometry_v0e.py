def score_candidate(p:Path, year:int):
    n=norm(str(p))
    score=0
    if "skifte" in n: score+=10
    if str(year) in n: score+=20
    if "arslager" in n: score+=5
    if "skane" in n: score+=4
    if "2025" in n and year!=2025: score-=20
    return score

def candidate_files(year:int):
    c=[]
    for root in RAW_ROOTS:
        if not root.exists(): continue
        # First pass: filenames/path explicitly mentioning target year.
        for p in root.rglob("*.gpkg"):
            if str(year) in str(p) and "skifte" in norm(str(p)):
                c.append(p)
        for p in root.rglob("*.parquet"):
            if str(year) in str(p) and "skifte" in norm(str(p)):
                c.append(p)
    return sorted(set(c), key=lambda p:score_candidate(p,year), reverse=True)

def read_hist_candidate(path:Path, year:int, bbox):
    try:
        if path.suffix.lower()==".gpkg":
            g=gpd.read_file(path, bbox=bbox)
        else:
            g=gpd.read_parquet(path)
            if g.crs and bbox:
                # bbox filter manually only after CRS conversion if needed
                pass
        if g.empty or "geometry" not in g.columns or g.crs is None:
            return None
        yc=year_col(g.columns)
        if yc:
            yy=pd.to_numeric(g[yc],errors="coerce")
            vals=set(int(v) for v in yy.dropna().unique()[:30])
            if year in vals or len(vals)>1:
                g=g[yy==year].copy()
        return g
    except Exception:
        return None

